def local_intents(root):
    """Замыслы, которые описывает сам экземпляр: его корпус, его реестры, его рабочие папки.

    Механизм о них не знает и знать не должен: у постороннего своя тема, своя раскладка и свои реестры. Файл
    `_staging/map-intents.local.tsv` ведёт владелец экземпляра (в поставку не идёт), а карта читает его вместе
    со своей таблицей: тогда документ объясняет структуру этой копии, а механика остаётся агностической.
    Разбор инвентаризации 2026-09-22: `_staging/cards/`, `raw/articles/`, `wiki/Clippings/` и им подобные —
    материал экземпляра, и требовать их от постороннего значит требовать его данных.
    """
    out = {}
    try:
        import domain
    except ImportError:
        return out
    path = domain.map_intents_path(root)
    if not path or not os.path.exists(path):
        return out
    for line in io.open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) >= 2 and parts[0].strip():
            out[parts[0].strip()] = parts[1].strip()
    return out


INSTANCE_INTENT_OVERRIDES = {"log.md"}


def all_intents(root):
    """Таблица механизма плюс замыслы экземпляра: в этом дереве объяснено всё значимое, и то, и другое."""
    local = local_intents(root)
    overlap = sorted((set(local) & set(INTENT)) - INSTANCE_INTENT_OVERRIDES)
    if overlap:
        raise ValueError("локальный intent конфликтует с механизмом: " + ", ".join(overlap))
    merged = dict(INTENT)
    merged.update(local)
    return merged


def tree_paths(root):
    """Множество относительных путей (каталоги и файлы) — форма дерева без размеров."""
    out = set()
    for r, dirs, fs in os.walk(root):
        _rel_here = os.path.relpath(r, root).replace("\\", "/")
        # Дерево — то, что видит версионный контроль: папка, целиком ушедшая в игнор (`node_modules` инструмента,
        # кеши), структурой проекта не является, и объяснять её карте нечего. Без этого §29 требовал замысел для
        # `.opencode/node_modules` — папки, которой в истории нет (найдено 2026-09-24).
        if _rel_here != ".":
            dirs[:] = sorted(d for d in dirs
                             if d not in IGNORED_DIRS and not _ignored(root, f"{_rel_here}/{d}"))
        else:
            dirs[:] = sorted(d for d in dirs if d not in IGNORED_DIRS)
        # Архив, temp и слой проходов — не структура поставки: архив целиком вне git (решение владельца 2026-09-21),
        # temp живёт до конца задачи, `_staging/audit` — выходы проходов, которые создаются после снятия отпечатка.
        # В отпечаток дерева они не входят, иначе карта старела бы каждый день и на каждом проходе.
        if _rel_here.startswith(("_staging/archive", "_staging/temp", "_staging/audit")):
            dirs[:] = []
            continue
        rel = os.path.relpath(r, root)
        if rel != ".":
            out.add(rel.replace("\\", "/"))
        for f in fs:
            rel_p = os.path.join(rel, f).replace("\\", "/") if rel != "." else f
            # Имя с `.local.` — файл экземпляра: его ведёт владелец, поставка его не несёт, и объяснять его
            # механизму нечего (соглашение введено 2026-09-22 вместе с замыслами раскладки экземпляра).
            if rel_p in SELF_OUTPUTS or DATED.search(f) or ".local." in f or rel_p in IGNORED_FILES:
                continue
            out.add(rel_p)
    return out


def fingerprint(root):
    paths = sorted(tree_paths(root))
    return hashlib.sha256("\n".join(paths).encode("utf-8")).hexdigest(), len(paths), paths


def dir_stats(root, rel):
    """Считает по тем же правилам, что отпечаток: датированные выходы генераторов и сама карта не в счёте.
    Иначе число файлов расходилось бы с проверкой и старело бы молча при каждом новом отчёте за день."""
    p = os.path.join(root, rel)
    n = sz = 0
    for r, dirs, fs in os.walk(p):
        dirs[:] = [d for d in dirs if d not in IGNORED_DIRS]
        for f in fs:
            if DATED.search(f):
                continue
            rp = os.path.join(os.path.relpath(r, root), f).replace("\\", "/") if os.path.relpath(r, root) != "." else f
            if rp in SELF_OUTPUTS:
                continue
            n += 1
            try: sz += os.path.getsize(os.path.join(r, f))
            except OSError: pass
    return n, sz


def intent_for(rel, ints):
    """intent ищется и с хвостовой косой чертой, и без неё: ключи рукописные, спотыкаться об это не надо.
    Таблица приходит снаружи: к таблице механизма добавляются замыслы экземпляра (`all_intents`)."""
    return ints.get(rel) or ints.get(rel.rstrip("/")) or ints.get(rel + "/")


