def intent_pair(value):
    """Пара «что это / зачем» из записи INTENT.

    Часть записей заведена одной строкой (13 добавлены 2026-09-17, ещё около двадцати — раньше), а генератор
    карты ждёт пару и падал с `ValueError: too many values to unpack` — карта структуры из-за этого не
    собиралась вовсе. Здесь строка делится по первому предложению: первая часть отвечает «что это», вторая —
    «зачем»; текст не переписывается и не теряется. Записи-пары возвращаются как есть.
    """
    if isinstance(value, (tuple, list)):
        parts = list(value) + [""] * (2 - len(value))
        return parts[0], parts[1]
    text = str(value).strip()
    m = re.match(r"(.*?\.)\s+(.*)", text, re.DOTALL)
    return (m.group(1), m.group(2)) if m else (text, "")


