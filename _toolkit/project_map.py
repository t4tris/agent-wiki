def check_supply_named(root):
    """Каждый файл поставки назван в карте: обход дерева против имён в карте.

    Узел объясняется записью замысла, листья перечислены под своим узлом по именам. Именем считается
    базовое имя или относительный путь в обратных кавычках текста карты; имя, встречающееся у нескольких
    файлов поставки, засчитывается только полным путём — иначе новый однофамилец проходит молча.
    Игнорируемые каталоги обходятся как в отпечатке: рабочая грязь не требует объяснений, её требуют удалять.
    Обе величины считаются обходом в момент запуска, а не вписаны: вписанное число протухает молча.
    """
    import supply as _supply
    pm = toolkit.area(root, os.path.relpath(MAP_MD, toolkit.AREA))
    try:
        spans = set(re.findall(r"`([^`]+)`", open(pm, encoding="utf-8").read()))
    except OSError as exc:
        return ["карта не прочитана: %s" % exc]
    rels = []
    for r, dirs, fs in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d not in _supply.SKIP_DIRS and d != ".git"
                         and not _ignored(root, os.path.relpath(os.path.join(r, d), root).replace("\\", "/")))
        for f in sorted(fs):
            rel = os.path.relpath(os.path.join(r, f), root).replace("\\", "/")
            if not _supply.included(rel):
                continue
            if DATED.search(os.path.basename(rel)):
                continue
            rels.append(rel)
    counts = {}
    for rel in rels:
        counts[os.path.basename(rel)] = counts.get(os.path.basename(rel), 0) + 1
    unnamed = []
    for rel in rels:
        base = os.path.basename(rel)
        if counts[base] > 1:
            ok = rel in spans
        else:
            ok = base in spans or rel in spans
        if not ok:
            unnamed.append(rel)
    print("поставка: файлов %d, в карте названо %d" % (len(rels), len(rels) - len(unnamed)))
    issues = []
    for rel in unnamed:
        issues.append(f"файл поставки не назван в карте: {rel} — объясни узел и перечисли листья")
    return issues


def cmd_check(root):
    """Для линтера §29: карта устарела или intent не покрыт — печатаем строки-проблемы."""
    issues = []
    pm = toolkit.area(root, os.path.relpath(MAP_MD, toolkit.AREA))
    if not os.path.exists(pm):
        print("- нет _staging/project-map.md: структура проекта не объяснена")
        return 1
    head = open(pm, encoding="utf-8").read()[:1200]
    fp_now, npaths, _ = fingerprint(root)
    import re
    m = re.search(r"отпечаток: `([0-9a-f]+)`", head)
    if not m:
        issues.append("карта без отпечатка дерева: пересобери project_map.py generate")
    elif not fp_now.startswith(m.group(1)):
        issues.append(f"карта устарела: отпечаток дерева {fp_now[:16]} против записанного {m.group(1)}")
    # Ключ карты, которому больше нечего объяснять: файл переехал или удалён, а строка осталась врать.
    # Сегодня таких нет — проверка стоит на переименование и переезд, а не на текущий дефект.
    for rel in sorted(all_intents(root)):
        if rel.rstrip("/") == "raw" or rel.startswith("raw/") or rel.rstrip("/").startswith(EMERGENT):
            continue  # корпус и выходы самого механизма: до первой волны их просто ещё нет
        if not os.path.exists(os.path.join(root, rel.rstrip("/"))):
            # Игнорируемое и архивное в поставку не входит: в свежей копии таких каталогов нет вовсе, и объявлять
            # их «переехавшими» значит ругаться на саму поставку. Считаем это нормой (находка приёмки 2026-09-21).
            if _ignored(root, rel.rstrip("/")):
                continue
            issues.append(f"intent без файла: {rel} — путь переехал или удалён, обнови карту")
    must, missing = coverage(root, tree_paths(root))
    for mis in missing:
        issues.append(f"структура без объяснения: {mis} — добавь строку intent в project_map.py")
    for sup in check_supply_named(root):
        issues.append(sup)
    for i in issues:
        print("- " + i)
    return 1 if issues else 0


