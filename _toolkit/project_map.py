def _ignored(root, rel):
    """Путь, не входящий в поставку по .gitignore: его отсутствие — не «переехал», а «не поставляется»."""
    rel = rel.replace("\\", "/").lstrip("/")
    try:
        r = subprocess.run(["git", "-C", root, "check-ignore", "--no-index", "-q", rel],
                           capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=30, check=False)
        if r.returncode == 0:
            return True
    except (OSError, subprocess.TimeoutExpired):
        verdict = False
    try:
        import fnmatch
        for gi in (os.path.join(root, ".gitignore"), toolkit.script(os.path.join("tools", "tg-saved", ".gitignore"), root)):
            if not os.path.exists(gi):
                continue
            for line in open(gi, encoding="utf-8").read().split("\n"):
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                negate = line.startswith("!")
                pat = (line[1:].strip() if negate else line).lstrip("/")
                if not pat:
                    continue
                if (fnmatch.fnmatch(rel, pat) or rel == pat.rstrip("/") or rel.startswith(pat.rstrip("/") + "/")
                        or fnmatch.fnmatch(os.path.basename(rel), pat.rstrip("/"))):
                    return not negate
    except (OSError, UnicodeError) as exc:
        print("project-map: правила исключения не прочитаны: %s" % exc, file=sys.stderr)
        return False
    return False


