def coverage(root, paths):
    """Что обязано иметь объяснение: каталоги до 2-го уровня, файлы в корне, скрипты и документы в `_toolkit`."""
    must, missing = [], []
    for p in sorted(paths):
        d = p.count("/")
        if d == 0 and "." in p:
            must.append(p)
        elif p.startswith("_toolkit/") and d == 1 and p.endswith((".py", ".md", ".ps1", ".tsv")) and p not in DERIVED_OUTPUTS:
            must.append(p)
        elif p.startswith("_staging/") and d == 1 and p.endswith((".py", ".md", ".ps1", ".tsv")) and p not in DERIVED_OUTPUTS:
            must.append(p)
        elif d <= 1 and not os.path.splitext(p)[1]:
            must.append(p)
    for m in must:
        if ".local." in m:
            continue                      # файл экземпляра: механизм его не объясняет и в поставку не несёт
        if intent_for(m, all_intents(root)): continue
        if m.startswith(("raw/",) + EMERGENT):
            continue  # корпус и выходы механизма объясняются строкой-образцом, а не поимённо
        base = os.path.basename(m)
        if any(s[0] == base for s in MACHINERY): continue
        missing.append(m)
    return must, missing


def collect(root):
    """Дерево до второго уровня: ровно та глубина, на которой проект объясняется, а не описывается."""
    nodes = []
    def add(rel, level):
        fp = os.path.join(root, rel)
        if os.path.isdir(fp):
            n, sz = dir_stats(root, rel)
            nodes.append({"rel": rel, "kind": "dir", "level": level, "n": n, "sz": sz})
            if level >= 1:
                return  # глубже второго уровня проект не объясняется, а дробится: там правит intent родителя
            for child in sorted(os.listdir(fp)):
                cfp = os.path.join(fp, child)
                if os.path.isdir(cfp) and child not in IGNORED_DIRS:
                    add(rel + "/" + child, level + 1)
    for name in sorted(os.listdir(root)):
        if name in IGNORED_DIRS:
            continue
        fp = os.path.join(root, name)
        if os.path.isdir(fp):
            add(name, 0)
        else:
            nodes.append({"rel": name, "kind": "file", "level": 0, "n": 1, "sz": os.path.getsize(fp)})
    return nodes


def human(sz):
    for unit, div in (("ГБ", 1 << 30), ("МБ", 1 << 20), ("КБ", 1 << 10)):
        if sz >= div: return f"{sz / div:.1f} {unit}"
    return f"{sz} б"


def build(root):
    fp, npaths, paths = fingerprint(root)
    must, missing = coverage(root, paths)
    tree = collect(root)
    return dict(fingerprint=fp, paths=npaths, must=len(must), missing=missing, tree=tree,
                date=datetime.date.today().isoformat())


