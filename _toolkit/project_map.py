def relocated_intent(path):
    if path == "SCHEMA.md":
        return "_toolkit/SCHEMA.md"
    if path == "fixture" or path.startswith("fixture/"):
        return "_toolkit/" + path
    if path.startswith("_staging/hooks/"):
        return "_toolkit/hooks/" + path.split("/", 2)[2]
    if path.startswith("_staging/"):
        name = path.split("/", 1)[1]
        if "/" not in name and (name.endswith(".py") or name in MECHANISM_DOCS):
            return "_toolkit/" + name
    if path.startswith("_tools/tg-saved/") and (
            path.endswith(".py") or path in ("_tools/tg-saved/README.md", "_tools/tg-saved/.gitignore")):
        return "_toolkit/tools/tg-saved/" + path.split("/", 2)[2]
    return path


