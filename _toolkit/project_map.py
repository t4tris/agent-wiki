def check_mirror_writable(root):
    import stat as _stat
    bad = []
    base = toolkit.wiki(root, "sources")
    for r, dirs, fs in os.walk(base):
        for f in fs:
            fp = os.path.join(r, f)
            try:
                if not (os.stat(fp).st_mode & _stat.S_IWRITE):
                    bad.append(os.path.relpath(fp, root))
            except OSError:
                bad.append(os.path.relpath(fp, root) + " (нет доступа)")
    return [f"{b}: файл только для чтения" for b in bad]


def check_vault_clean(root):
    bad = []
    for r, dirs, fs in os.walk(toolkit.wiki(root)):
        dirs[:] = [d for d in dirs if d != ".obsidian"]
        for f in fs:
            if re.fullmatch(r"(log\.md|SCHEMA.*\.md)", f) or f.endswith((".tsv", ".py", ".ps1", ".json", ".csv")):
                bad.append(os.path.relpath(os.path.join(r, f), root))
    return [f"{b}: служебный файл внутри хранилища" for b in bad]


def check_frozen_untouched(root):
    """«Опубликованные слепки не правятся никогда» — из раздела границ карты. Проверяется историей:
    ни один коммит не должен менять содержимое уже замороженного файла."""
    if not os.path.exists(os.path.join(root, ".git")):
        return []                    # копия без истории: проверять нечем
    try:
        r = subprocess.run(["git", "log", "--diff-filter=M", "--name-only", "--pretty=format:",
                            "--", "_staging/audit/handover/"], cwd=root, capture_output=True,
                           text=True, encoding="utf-8", errors="replace", check=False)
    except (OSError, UnicodeError) as ex:
        return ["git log не прочитал историю frozen-слепков: %s" % ex]
    if r.returncode != 0:
        detail = (getattr(r, "stderr", "") or "").strip()
        suffix = ": " + detail if detail else ""
        return ["git log не прочитал историю frozen-слепков (код %d)%s" % (r.returncode, suffix)]
    out = r.stdout
    touched = sorted({l.strip() for l in out.splitlines() if l.strip()})
    return [f"{f}: слепок изменялся после создания — это уже не слепок" for f in touched]


def check_tooling_ignored(root):
    if not os.path.isdir(os.path.join(root, ".git")):
        return []                    # копия без истории: проверять нечем, и выдумывать дефект нельзя
    bad = []
    for rel in ("_tools/tg-saved/models/gigaam/v3_e2e_ctc.int8.onnx", ".venv/pyvenv.cfg",
                "_tools/tg-saved/export/.keep"):
        r = subprocess.run(["git", "check-ignore", "-q", rel], cwd=root, capture_output=True, check=False)
        if r.returncode != 0:
            bad.append(f"{rel}: не игнорируется (проверь .gitignore в папке обвязки)")
    return bad


ASSERTION_CHECKS = {
    "зеркало-записываемое": check_mirror_writable,
    "хранилище-без-служебного": check_vault_clean,
    "слепки-не-правятся": check_frozen_untouched,
    "обвязка-вне-git": check_tooling_ignored,
}


def cmd_verify(root):
    """Для линтера §31: подтверждаются ли следствия утверждений карты. Печатает строки-проблемы."""
    issues, checked = [], 0
    for name, claim, why in ASSERTIONS:
        fn = ASSERTION_CHECKS[name]
        try:
            found = fn(root)
        except (ImportError, OSError, RuntimeError, ValueError, KeyError, TypeError, IndexError, AttributeError) as ex:
            found = [f"проверка «{name}» упала: {ex}"]
        checked += 1
        issues += found
    if os.environ.get("PROJECT_MAP_VERIFY_VERBOSE"):
        print(f"проверено утверждений: {checked}")
    for i in issues:
        print("- " + i)
    return 1 if issues else 0


