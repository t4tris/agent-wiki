"""Имя страницы из имени понятия: автоматически, без человека.

Владелец 2026-09-17: «убери поле slug, нейминг должен быть автоматическим без человека». И отдельно: «в
отчет почему-то попадают названия страницы на кириллице, хотя фактически у нас все названия статей на
латинице». Причина была в том, что слаг собирался вырезанием не-латиницы из имени понятия: у «воркер»
остаётся пустая строка, а пустой слаг агент заполнял как мог — отсюда и поле ввода, и кириллица.

Правило простое и повторяет то, как корпус называет понятия сам:
1. в скобках после русского имени обычно стоит английский термин — «воркер (worker, исполнитель)» → `worker`;
   берём первое латинское слово из скобок, это имя понятия в корпусе, а не перевод;
2. латиницы в скобках нет — это отказ: `ValueError`; слаг из транслитерации не собирается (2026-09-17);
3. имя уже латинское — берём его как есть.

    from slugify import slug_for
    slug_for("воркер (worker, исполнитель)")   # 'worker'
    slug_for("графовая инженерия (graph engineering)")   # 'graph-engineering'
"""
import re

TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh", "з": "z",
    "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
    "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def _clean(text):
    text = text.lower().replace("_", "-")
    text = re.sub(r"[^a-z0-9\-]+", "-", text)
    return re.sub(r"-{2,}", "-", text).strip("-")


def slug_for(name):
    """Слаг страницы по имени понятия: латинский, устойчивый, никогда не пустой."""
    name = (name or "").strip()
    # 1) английский термин в скобках — так корпус называет понятие сам
    for chunk in re.findall(r"\(([^)]*)\)", name):
        for part in chunk.split(","):
            part = part.strip()
            # целая латинская фраза в скобках — это и есть имя понятия в корпусе: «context window»,
            # «graph engineering». Одиночный латинский термин рядом с русским словом тоже годится: «worker».
            if part and re.fullmatch(r"[A-Za-z0-9\-\. ]+", part):
                slug = _clean(part)
                if slug:
                    return slug
    # 2) латинская часть до скобок
    base = re.sub(r"\([^)]*\)", " ", name)
    latin = _clean(base)
    if latin:
        return latin
    # 3) английского термина нет — и это отказ, а не повод транслитерировать.
    # Владелец 2026-09-17: «четыре понятия всё ещё кириллицей, хотя нужны английские термины / латиница,
    # в итоге имеем нелепые слаги: stek вместо stack, planirovschik вместо planner». Причина была здесь:
    # транслитерация молча подставляла `kontekstnoe-okno` там, где понятию нужен термин `context-window`.
    raise ValueError(
        "у понятия нет английского термина: «%s» — назови термин в скобках, слаг из транслитерации не собирается"
        % name)
